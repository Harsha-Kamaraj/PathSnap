"""PathSnap data cleaning (decisions: docs/DATA_QUALITY_NOTES.md, code: src/pathsnap/cleaning.py).

Run from the repo root, inside the venv:
    python scripts/run_cleaning.py

Cleans every trip in the local partitions (train, student_test). No rows are
deleted and nothing is fitted, so this does not leak between partitions.

Outputs (deterministic):
    data/processed/<partition>/<trip_id>/{track,nodes,arcs,route}.csv.gz + meta.json
        (git-ignored; regenerate with this script)
    outputs/cleaning/cleaning_summary.csv   one row per trip (committed as evidence)
    outputs/cleaning/CLEANING_REPORT.md     what was flagged and what was excluded
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

import pandas as pd  # noqa: E402

from pathsnap import cleaning as C  # noqa: E402
from pathsnap.data_io import data_root, list_partitions, list_trips  # noqa: E402

OUT = REPO / "outputs" / "cleaning"
OUT.mkdir(parents=True, exist_ok=True)


def main():
    root = data_root()
    rows = []
    t0 = time.time()
    for part in list_partitions(root):
        for tid in list_trips(part, root):
            m = C.clean_and_save(part, tid)
            rows.append({k: v for k, v in m.items() if k != "thresholds"})
            print(f"{part}/{tid}: {m['n_fixes']} fixes, {m['n_segments']} segment(s), "
                  f"reliable {m['frac_label_reliable']:.0%}" + ("  EXCLUDED" if m["exclude_from_training"] else ""))
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "cleaning_summary.csv", index=False)
    write_report(df)
    print(f"done in {time.time() - t0:.0f}s -> {C.PROCESSED_ROOT.relative_to(REPO)}, {OUT.relative_to(REPO)}")


def write_report(df: pd.DataFrame):
    g = df.groupby("partition")
    fixes = g["n_fixes"].sum()
    L = ["# PathSnap: Cleaning Report (auto-generated by `scripts/run_cleaning.py`)", "",
         "Cleaning **never deletes rows**: every GPS fix still needs a prediction. It adds metres "
         "(per-trip UTM), segment / stop ids and quality flags. Thresholds are hand-set in "
         "`src/pathsnap/cleaning.py` and explained in `docs/DATA_QUALITY_NOTES.md`.", "",
         "## Thresholds", "",
         "| name | value | meaning |", "|---|---|---|",
         f"| SEGMENT_GAP_S | {C.SEGMENT_GAP_S:g} s | a longer time gap starts a new segment |",
         f"| MAX_SPEED_MPS | {C.MAX_SPEED_MPS:g} m/s | faster steps get `is_fast_step` (speed not trusted) |",
         f"| STOP_WINDOW / STOP_RADIUS_M | {C.STOP_WINDOW} fixes / {C.STOP_RADIUS_M:g} m | moved less than this = stopped |",
         f"| OFF_NETWORK_M | {C.OFF_NETWORK_M:g} m | fix farther than this from every road |",
         f"| FAR_FROM_ROUTE_M | {C.FAR_FROM_ROUTE_M:g} m | fix farther than this from its reference route (label check) |",
         f"| EXCLUDE_TRIP_FAR_FRAC | {C.EXCLUDE_TRIP_FAR_FRAC:.0%} | trip dropped from training above this share of far fixes |",
         "", "## Per partition", "",
         "| partition | trips | fixes | extra segments from gaps | spikes | fast steps | stopped fixes "
         "| off-network fixes | far-from-route fixes | label-reliable fixes | trips excluded |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for part, s in g:
        n = fixes[part]
        far = (s["frac_far_from_route"] * s["n_fixes"]).sum()
        rel = (s["frac_label_reliable"] * s["n_fixes"]).sum()
        L.append(f"| {part} | {len(s)} | {n:,} | {int((s['n_segments'] - 1).sum())} | {int(s['n_spikes'].sum())} "
                 f"| {int(s['n_fast_steps'].sum())} | {(s['frac_stop'] * s['n_fixes']).sum() / n:.1%} "
                 f"| {(s['frac_off_network'] * s['n_fixes']).sum() / n:.1%} | {far / n:.1%} | {rel / n:.1%} "
                 f"| {int(s['exclude_from_training'].sum())} |")
    L += ["", "## Road networks", "",
          f"* Zero-length arcs (never candidates): {int(df['n_zero_length_arcs'].sum())}.",
          f"* Geometric duplicate arcs mapped to a canonical arc id: {int(df['n_duplicate_arcs'].sum())}. "
          f"Reference-route entries that use a non-canonical duplicate: {int(df['route_uses_duplicate_arc'].sum())} "
          "(score predictions on `canonical_arc_id` so identical roads count as the same).",
          f"* Route breaks kept as-is and flagged (`break_before`): {int(df['route_breaks'].sum())}.",
          "", "## Trips excluded from training", ""]
    ex = df[df["exclude_from_training"]]
    if ex.empty:
        L.append("None.")
    else:
        L += ["| partition | trip_id | reason |", "|---|---|---|"]
        L += [f"| {r.partition} | {r.trip_id} | {r.exclude_reason} |" for r in ex.itertuples()]
        L.append("")
        L.append("Excluded trips stay in `data/processed` with all flags. For student_test this only "
                 "affects the \"reliable fixes only\" metric; metrics on all fixes are reported too.")
    L += ["", "## Most affected trips (lowest share of label-reliable fixes)", "",
          "| partition | trip_id | fixes | segments | stopped | off-network | far from route | reliable |",
          "|---|---|---|---|---|---|---|---|"]
    for r in df.nsmallest(10, "frac_label_reliable").itertuples():
        L.append(f"| {r.partition} | {r.trip_id} | {r.n_fixes} | {r.n_segments} | {r.frac_stop:.0%} "
                 f"| {r.frac_off_network:.0%} | {r.frac_far_from_route:.0%} | {r.frac_label_reliable:.0%} |")
    L += ["", "## Output files (`data/processed/<partition>/<trip_id>/`)", "",
          "* `track.csv.gz`: one row per raw fix (same order). `fix_idx, lon, lat, t, t_rel, dt_prev, x, y, "
          "step_m, speed_mps, segment_id, is_spike, is_fast_step, is_stop, stop_id, d_net_m, is_off_network` "
          "are **label-free**. `d_route_m, is_far_from_route, label_reliable` use the route and must never "
          "be model inputs.",
          "* `nodes.csv.gz`: `node_id, lon, lat, x, y`.",
          "* `arcs.csv.gz`: `arc_id, from_node, to_node, length_m, is_self_loop, is_zero_length, "
          "canonical_arc_id, is_duplicate, in_largest_scc, is_candidate`.",
          "* `route.csv.gz`: `seq, arc_id, canonical_arc_id, break_before, is_uturn, is_revisit`.",
          "* `meta.json`: UTM zone, counts, exclusion decision and thresholds.", ""]
    (OUT / "CLEANING_REPORT.md").write_text("\n".join(L))


if __name__ == "__main__":
    main()
